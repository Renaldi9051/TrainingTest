// Cerminan BE/src/lib/slug.ts untuk pratinjau slug di form. BE tetap yang memvalidasi saat simpan.
export const SLUG_MAX_LENGTH = 120;

export function slugify(input: string): string {
  return input
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/&/g, " dan ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, SLUG_MAX_LENGTH)
    .replace(/-+$/g, "");
}
